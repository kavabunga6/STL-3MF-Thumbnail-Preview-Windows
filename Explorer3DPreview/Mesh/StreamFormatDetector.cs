using System.Text;

namespace Explorer3DPreview.Mesh;

internal static class StreamFormatDetector
{
    internal static string Detect(Stream stream)
    {
        var originalPosition = stream.Position;
        try
        {
            stream.Position = 0;
            var prefix = new byte[(int)Math.Min(64 * 1024, stream.Length)];
            var total = 0;
            while (total < prefix.Length)
            {
                var read = stream.Read(prefix, total, prefix.Length - total);
                if (read <= 0) break;
                total += read;
            }
            var bytes = total == prefix.Length ? prefix : prefix[..total];
            if (bytes.Length >= 4 && bytes[0] == (byte)'P' && bytes[1] == (byte)'K' && bytes[2] == 3 && bytes[3] == 4)
                return ".3mf";

            if (stream.Length >= 84 && bytes.Length >= 84)
            {
                var triangleCount = BitConverter.ToUInt32(bytes, 80);
                if (84L + triangleCount * 50L == stream.Length) return ".stl";
            }

            var text = Encoding.UTF8.GetString(bytes).TrimStart('\uFEFF', ' ', '\t', '\r', '\n');
            if (text.StartsWith("ISO-10303-21", StringComparison.OrdinalIgnoreCase)) return ".step";
            if (text.StartsWith("ply", StringComparison.OrdinalIgnoreCase)) return ".ply";
            if (text.StartsWith("OFF", StringComparison.OrdinalIgnoreCase)) return ".off";
            if (text.Contains("<amf", StringComparison.OrdinalIgnoreCase)) return ".amf";
            if (text.StartsWith("solid", StringComparison.OrdinalIgnoreCase) &&
                text.Contains("facet", StringComparison.OrdinalIgnoreCase)) return ".stl";

            var lines = text.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(line => line.TrimStart()).ToArray();
            // "v x y z" lines only exist in OBJ. Exporters write every vertex first, so in a big file the first
            // "f" line can be far beyond this window: a vertex line is enough.
            if (lines.Any(IsObjVertexLine)) return ".obj";
            if (lines.Any(line => line.StartsWith("G0", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith("G1", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith("G28", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith("G21", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith("M82", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith("M83", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith("M104", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith("M109", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith("; thumbnail begin", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith("; generated by", StringComparison.OrdinalIgnoreCase) ||
                                  line.StartsWith(";FLAVOR", StringComparison.OrdinalIgnoreCase)))
                return ".gcode";
            return ".stl";
        }
        finally { stream.Position = originalPosition; }
    }

    private static bool IsObjVertexLine(string line)
    {
        if (!line.StartsWith("v ", StringComparison.Ordinal)) return false;
        var parts = line.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
        return parts.Length >= 4 &&
               float.TryParse(parts[1], System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out _) &&
               float.TryParse(parts[2], System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out _) &&
               float.TryParse(parts[3], System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out _);
    }
}
